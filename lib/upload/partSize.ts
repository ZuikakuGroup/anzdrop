import { CHUNK_SIZE } from "@/lib/crypto/types";

// R2マルチパートアップロードの1パートあたりのサイズ。
//
// R2は「最終パートを除く全パートが同一サイズであること」かつ「最終パート以外は
// 5MiB以上であること」を要求する。クライアントは暗号化ストリーム
// (先頭のファイルsalt + 各パケット)を、パケット境界とは無関係にこの固定サイズで
// 切り出してアップロードし、最終パートだけがこれ未満になるようにする。
//
// 先頭パケットにだけ付くファイルsalt(FILE_SALT_LENGTH=16B)の分だけ「1パケット=
// 1パート」方式では先頭パートが他より大きくなり、3パート以上のアップロードで
// complete()が必ず失敗していた(GitHub issue #34)。パケットと切り離して
// 固定サイズで詰め直すことでこれを防ぐ。ストレージ上のバイト列自体は
// 「salt + 全パケットの連結」で従来と一切変わらないため、ダウンロード・復号側の
// 実装には影響しない。
export const UPLOAD_PART_SIZE = CHUNK_SIZE; // 8 MiB
